#!/usr/bin/env node
// Turns every DECLARED asset key with no file behind it into a marked placeholder.
//
//   node scripts/build-placeholders.mjs      ->  dist/placeholders.css
//
// WHY THIS EXISTS, AND WHY IT IS DANGEROUS. Nineteen slots across five screens show a
// photograph in the design and nothing on the page, because www.figma.com is blocked here. The
// screens need to be presentable before the real assets arrive.
//
// That request is one step away from the exact mistake F-026 was written about:
//
//     a graceful fallback is a failure mode that reports success
//
// A tinted panel looks deliberate. Fill every slot with one and verify-images goes green, and a
// genuinely missing picture is invisible again — the monogram problem with better art.
//
// So the one rule this file exists to enforce: A PLACEHOLDER IS NEVER SILENT. Every rule below
// carries `--pf-placeholder: 1`, verify-images.mjs reads it, counts it, and names the key in
// its verdict line on every run. A stand-in that is counted is not a fallback; it is a tracked
// state with a number on it.
//
// PRECEDENCE NEEDS NO SPECIFICITY GAMES. A placeholder is emitted only for a key with no real
// file. Drop `nicholas-smudge.png` into assets/avatars/ and this stops generating a rule for
// it — dist/avatars.css takes over and the key drops out of the placeholder count by itself.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { extname, basename } from 'node:path';

const IMG_DIR = 'assets/images', AV_DIR = 'assets/avatars';
const EXT = /\.(png|jpe?g|webp)$/i;

const filesIn = (dir) => (existsSync(dir)
  ? new Set(readdirSync(dir).filter((f) => EXT.test(f)).map((f) => basename(f, extname(f)).toLowerCase()))
  : new Set());

// The keys come from the extracts, so a slot nobody declared gets no placeholder — the same
// declaration the screens already bind to, not a second list to keep in step.
function declaredKeys() {
  const images = new Map(), avatars = new Map();
  for (const f of readdirSync('prototypes').filter((f) => f.endsWith('.figma.json')).sort()) {
    const d = JSON.parse(readFileSync(`prototypes/${f}`, 'utf8'));
    for (const e of d.images || []) {
      if (e && e.key) images.set(e.key, (images.get(e.key) || 0) + 1);
    }
    for (const [name, v] of Object.entries(d.portraits || {})) {
      if (v && typeof v === 'object' && v.key) avatars.set(v.key, (avatars.get(v.key) || 0) + 1);
    }
  }
  return { images, avatars };
}

mkdirSync('dist', { recursive: true });
const have = { images: filesIn(IMG_DIR), avatars: filesIn(AV_DIR) };
const want = declaredKeys();

const missingImages = [...want.images.keys()].filter((k) => !have.images.has(k)).sort();
const missingAvatars = [...want.avatars.keys()].filter((k) => !have.avatars.has(k)).sort();

const out = [];
out.push('/* People First — placeholders for assets that have not arrived. GENERATED by');
out.push(' * scripts/build-placeholders.mjs. Do not hand-edit.');
out.push(' *');
out.push(' * A PLACEHOLDER IS NEVER SILENT. Every rule here sets --pf-placeholder: 1, which');
out.push(' * scripts/verify-images.mjs reads, counts, and names in its verdict line on every run.');
out.push(' * That is the whole safeguard: a tinted panel looks deliberate, so the only thing');
out.push(' * stopping it becoming permanent by accident is that the count never goes away.');
out.push(' *');
out.push(' * Emitted ONLY for a declared key with no file behind it. Drop the real file into');
out.push(' * assets/images/ or assets/avatars/ and the rule stops being generated — no override,');
out.push(' * no specificity contest, and the key leaves the placeholder count by itself.');
out.push(' */');
out.push('');

if (missingImages.length) {
  out.push('/* PAGE PICTURES — a flat theme tint. A token, so it re-resolves in dark mode, and no');
  out.push('   raw hex, no glyph and no invented imagery. It reads as a deliberate empty panel,');
  out.push('   which is exactly what it is. */');
  for (const k of missingImages) {
    out.push(`.pf-image[data-image="${k}"] {`);
    out.push('  --pf-placeholder: 1;');
    out.push('  background-image: linear-gradient(var(--pf-bg-theme), var(--pf-bg-theme));');
    out.push('}');
    out.push('');
  }
}

if (missingAvatars.length) {
  out.push('/* PEOPLE — marked, but deliberately NOT repainted. The monogram already standing in');
  out.push('   (NS, DT, SS) says more than a blank tinted disc would, and it is not a fabricated');
  out.push('   face. All this adds is the mark, so the slot is counted and named rather than');
  out.push('   failing as empty. The look does not change; only the reporting does. */');
  for (const k of missingAvatars) {
    out.push(`.pf-avatar-photo[data-avatar="${k}"] { --pf-placeholder: 1; }`);
  }
  out.push('');
}

const css = out.join('\n');
writeFileSync('dist/placeholders.css', css);

const total = missingImages.length + missingAvatars.length;
console.log(`built dist/placeholders.css  (${(css.length / 1024).toFixed(1)} KB)`);
if (!total) {
  console.log('placeholders     : 0 — every declared asset has a real file behind it');
} else {
  const slots = missingImages.reduce((n, k) => n + want.images.get(k), 0)
    + missingAvatars.reduce((n, k) => n + want.avatars.get(k), 0);
  console.log(`placeholders     : ${total} key(s) standing in across ${slots} slot(s)`);
  if (missingImages.length) console.log(`                   pictures: ${missingImages.join(', ')}`);
  if (missingAvatars.length) console.log(`                   people  : ${missingAvatars.join(', ')}`);
  console.log('                   drop the real files in assets/images/ and assets/avatars/');
}
