#!/usr/bin/env node
// Turns assets/images/*.{png,jpg,jpeg,webp} into dist/images.css.
//
//   node scripts/build-images-css.mjs
//
// WHY THIS EXISTS. The same seam as assets/avatars/, one level up: a screen's photographs.
// A Figma frame that shows a hero, a video still or a card image is showing PHOTOGRAPHY, and
// photography is not a design token — there is no variant to capture and no colour to bind, so
// it can never come out of dist/components.css.
//
// Base64, not a <link> or an <img src>, for the reason dist/fonts.css is base64: a self-
// contained artifact or a .dc.html canvas cannot reference a local file, and a screen that
// looks right in the repo and blank in an artifact is the failure this project keeps having.
//
// A MISSING FILE IS LOUD, NOT GRACEFUL. This is the one thing it does differently from
// avatars.css. There, a missing portrait degrades to a monogram — which read as deliberate and
// hid the fact that every avatar in the repo was empty for a day (F-026). A missing page image
// leaves the slot painting nothing at all, and scripts/verify-images.mjs FAILS on it. An empty
// directory here is not a quiet default; it is a red check with the key names in it.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { extname, basename } from 'node:path';

const DIR = 'assets/images';
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };
mkdirSync(DIR, { recursive: true });

const files = existsSync(DIR)
  ? readdirSync(DIR).filter((f) => MIME[extname(f).toLowerCase()]).sort()
  : [];

const out = [];
out.push('/* People First — page photographs. GENERATED by scripts/build-images-css.mjs.');
out.push(' * Do not hand-edit; drop images in assets/images/ and re-run the build.');
out.push(' *');
out.push(' * A file named hero-pathway.png binds to data-image="hero-pathway". Unlike an avatar,');
out.push(' * a missing page image does NOT degrade to something that looks deliberate — the slot');
out.push(' * paints nothing and scripts/verify-images.mjs fails it by name.');
out.push(' *');
out.push(' * SAMPLE DATA. These pictures stand in for content that does not exist. Nothing here');
out.push(" * should ever be paired with a real person's record.");
out.push(' */');
out.push('');
out.push('/* The slot keeps its declared size whether or not a file exists, so a missing picture');
out.push('   is a hole of the right shape rather than a collapsed box that hides the gap. */');
out.push('.pf-image[data-image] { background-size: cover; background-position: center; background-repeat: no-repeat; }');
out.push('');

let bytes = 0;
for (const f of files) {
  const key = basename(f, extname(f)).toLowerCase();
  const buf = readFileSync(`${DIR}/${f}`);
  bytes += buf.length;
  out.push(`.pf-image[data-image="${key}"] {`);
  out.push(`  background-image: url(data:${MIME[extname(f).toLowerCase()]};base64,${buf.toString('base64')});`);
  out.push('}');
  out.push('');
}

const css = out.join('\n');
writeFileSync('dist/images.css', css);

console.log(`built dist/images.css  (${(css.length / 1024).toFixed(0)} KB)`);
if (!files.length) {
  console.log('page images      : 0 — assets/images/ is empty, so every [data-image] slot paints nothing');
  console.log('                   verify-images will FAIL by name until files land there');
} else {
  console.log(`page images      : ${files.length} (${(bytes / 1024).toFixed(0)} KB of source images)`);
  console.log(`                   ${files.map((f) => basename(f, extname(f))).join(', ')}`);
}
