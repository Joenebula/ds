#!/usr/bin/env node
// Builds dist/tokens.css from tokens/design-tokens.json.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const t = JSON.parse(readFileSync('tokens/design-tokens.json', 'utf8'));
const ext = n => n.$extensions['com.mhr.pf'];

const collect = (node, acc = []) => {
  if (node && typeof node === 'object') {
    if (node.$type) acc.push(node);
    else Object.values(node).forEach(v => collect(v, acc));
  }
  return acc;
};

const decl = (name, value, comment) =>
  `  ${name}: ${value};${comment ? ` /* ${comment} */` : ''}`;

// --- primitives ---
const primitives = [...collect(t.color.base), ...collect(t.color.theme)]
  .map(n => decl(ext(n).cssVar, n.$value, ext(n).figmaName));

// --- scalars ---
const scalar = (group, label) => {
  const rows = collect(group).map(n => decl(ext(n).cssVar, Array.isArray(n.$value) ? n.$value.join(', ') : n.$value));
  return rows.length ? [`\n  /* ${label} */`, ...rows] : [];
};

const shadows = collect(t.shadow).map(n => decl(ext(n).cssVar, ext(n).css, ext(n).figmaName));
const gradients = collect(t.gradient).map(n => decl(ext(n).cssVar, n.$value, ext(n).figmaName));

// --- semantic, per mode ---
const semantic = collect(t.color.semantic);
const semanticFor = mode => semantic.map(n => {
  const e = ext(n);
  const ref = e.cssRef[mode];
  const raw = e.modes[mode];
  const value = ref ? `var(${ref})` : raw;
  return decl(e.cssVar, value, ref ? null : 'literal');
});

const light = semanticFor('light');
const dark = semanticFor('dark');

const header = `/* People First Design System — design tokens
 * GENERATED by scripts/build-css.mjs. Do not edit by hand.
 * Source: Figma file aRWjBnTvdLiG50xtwodGwH (People First Design System)
 *
 * Dark mode: set data-theme="dark" on <html>, or leave it unset and the
 * system preference applies. data-theme="light" pins light mode.
 */\n`;

const css = [
  header,
  ':root {',
  '  color-scheme: light dark;',
  '',
  '  /* ---- Primitive colours (Colours Primitive) ---- */',
  ...primitives,
  ...scalar(t.font, 'Font families'),
  ...scalar(t.fontSize, 'Font sizes'),
  ...scalar(t.fontWeight, 'Font weights'),
  ...scalar(t.space, 'Spacing'),
  ...scalar(t.radius, 'Radius'),
  ...scalar(t.iconSize, 'Icon sizes'),
  '\n  /* Shadows */',
  ...shadows,
  '\n  /* Gradients */',
  ...gradients,
  '',
  '  /* ---- Semantic colours — Lightmode ---- */',
  ...light,
  '}',
  '',
  '/* ---- Semantic colours — Darkmode (explicit) ---- */',
  ':root[data-theme="dark"] {',
  ...dark,
  '}',
  '',
  '/* ---- Semantic colours — Darkmode (system preference) ---- */',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  ...dark.map(l => '  ' + l),
  '  }',
  '}',
  ''
].join('\n');

mkdirSync('dist', { recursive: true });
writeFileSync('dist/tokens.css', css);

const varCount = (css.match(/^\s+--pf-/gm) || []).length;
console.log(`dist/tokens.css written — ${varCount} declarations, ${semantic.length} semantic tokens x 2 modes`);
