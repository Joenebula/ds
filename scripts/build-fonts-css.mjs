#!/usr/bin/env node
// Turns assets/fonts/*.woff2 into dist/fonts.css — the @font-face layer.
//
//   node scripts/build-fonts-css.mjs
//
// WHY THIS EXISTS. The design system had no font layer at all. `--pf-font-body` says
// `Open Sans, system-ui, sans-serif` and every type class asks for a weight, but nothing
// anywhere shipped the face. Open Sans arrived, when it arrived, from a Google Fonts <link>
// hand-written into four prototype files. Everywhere else — docs/components.html, the
// ds-bundle, every artifact and every .dc.html canvas built to the CLAUDE.md recipe — fell
// straight through to system-ui, which is SF Pro on a Mac and Segoe UI on Windows. Both are
// visibly lighter than Open Sans SemiBold at the same 600, which is why the weight was
// reported as reading "medium".
//
// Base64 rather than url(../assets/fonts/…) for the same reason build-components-gallery.mjs
// inlines rather than links: an artifact or canvas cannot reference a local file, and a
// stylesheet that silently does nothing is the worst way for a design system to fail.
//
// VARIABLE, not static. One file per subset/style covers wght 300-800, so every weight
// dist/type.css emits is served — including the 300 of .pf-text-xl-heading-light and the 500
// of .pf-text-mobile-xxl-heading, neither of which the old Google Fonts link even requested.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';

const DIR = 'assets/fonts';
const manifest = JSON.parse(readFileSync(`${DIR}/manifest.json`, 'utf8'));
const names = Object.keys(manifest).sort();
if (!names.length) { console.error(`no faces in ${DIR}/manifest.json`); process.exit(1); }

const out = [];
out.push('/* People First — the font layer. GENERATED by scripts/build-fonts-css.mjs.');
out.push(' * Do not hand-edit; re-run the build.');
out.push(' *');
out.push(' * Open Sans, variable (wght 300-800), self-hosted and base64-inlined so the face is');
out.push(' * present on every surface: a linked page, an inlined artifact, a .dc.html canvas, and');
out.push(' * a machine with no network. Nothing here depends on fonts.googleapis.com.');
out.push(' *');
out.push(' * face                                subset      style   bytes   sha256');
for (const n of names) {
  const m = manifest[n];
  out.push(` * ${n.padEnd(34)} ${m.subset.padEnd(11)} ${m.style.padEnd(7)} ${String(m.bytes).padStart(6)}  ${m.sha256.slice(0, 16)}…`);
}
out.push(' *');
out.push(' * Sources are recorded in assets/fonts/manifest.json so a re-fetch is verifiable.');
out.push(' * Open Sans is licensed under the SIL Open Font License 1.1.');
out.push(' */');
out.push('');

let bad = 0;
for (const n of names) {
  const m = manifest[n];
  const file = `${DIR}/${n}`;
  if (!existsSync(file)) { console.error(`missing face: ${file}`); bad++; continue; }
  const buf = readFileSync(file);
  const sha = createHash('sha256').update(buf).digest('hex');
  if (sha !== m.sha256) {
    // A face that does not match the manifest is not the face the CSS claims to carry.
    console.error(`${n}: sha256 ${sha.slice(0, 16)}… does not match manifest ${m.sha256.slice(0, 16)}…`);
    bad++; continue;
  }
  out.push('@font-face {');
  out.push("  font-family: 'Open Sans';");
  out.push(`  font-style: ${m.style};`);
  out.push(`  font-weight: ${m.weight};`);          // 300 800 — the variable range
  out.push('  font-display: swap;');
  out.push(`  src: url(data:font/woff2;base64,${buf.toString('base64')}) format('woff2');`);
  out.push(`  unicode-range: ${m.unicodeRange};`);
  out.push('}');
  out.push('');
}
if (bad) { console.error(`${bad} face(s) missing or altered — not writing dist/fonts.css`); process.exit(1); }

const css = out.join('\n');
writeFileSync('dist/fonts.css', css);

const raw = names.reduce((n, k) => n + manifest[k].bytes, 0);
console.log(`built dist/fonts.css  (${(css.length / 1024).toFixed(0)} KB from ${(raw / 1024).toFixed(0)} KB of woff2)`);
console.log(`faces            : ${names.length} (${names.filter(n => manifest[n].style === 'normal').length} normal, `
  + `${names.filter(n => manifest[n].style === 'italic').length} italic)`);
console.log(`weight range     : ${manifest[names[0]].weight} — variable, one file per subset`);
console.log(`network at runtime: none`);
