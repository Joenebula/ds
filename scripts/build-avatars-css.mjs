#!/usr/bin/env node
// Turns assets/avatars/*.{png,jpg,jpeg,webp} into dist/avatars.css.
//
//   node scripts/build-avatars-css.mjs
//
// WHY THIS EXISTS. Figma's `People` component carries a photograph per person, and
// tokens/_raw/uncaptured-reasons.tsv records why it is not in the library:
//
//   People  People  its variants are sample content (one per fictional employee), not design
//   Profile image  People  no variant binds a colour variable in Figma — nothing to put in a stylesheet
//
// Both are correct — a photograph is not a design token. But the consequence was that every
// prototype drew initials where the real product draws a face, and the screens stopped
// looking like the product. This is the seam: drop images in assets/avatars/ and they become
// a stylesheet, base64-inlined for the same reason dist/fonts.css is — an artifact or a
// .dc.html canvas cannot reference a local file.
//
// AN EMPTY DIRECTORY IS FINE AND SAYS SO. With no images this emits a stylesheet that binds
// nothing, and every `.avatar` keeps its initials. What it must never do is fail silently, so
// the build prints the count either way.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { extname, basename } from 'node:path';

const DIR = 'assets/avatars';
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp' };
mkdirSync(DIR, { recursive: true });

const files = existsSync(DIR)
  ? readdirSync(DIR).filter((f) => MIME[extname(f).toLowerCase()]).sort()
  : [];

const out = [];
out.push('/* People First — avatar photographs. GENERATED by scripts/build-avatars-css.mjs.');
out.push(' * Do not hand-edit; drop images in assets/avatars/ and re-run the build.');
out.push(' *');
out.push(' * Figma keeps these as sample content rather than library components, so they are');
out.push(' * not tokens and carry no variant. A file named aisha-bello.png binds to');
out.push(' * data-avatar="aisha-bello"; anything with no matching file keeps its initials.');
out.push(' *');
out.push(' * SAMPLE DATA. These portraits stand in for employees who do not exist. Nothing here');
out.push(' * should ever be paired with a real person\'s record.');
out.push(' */');
out.push('');
out.push('/* The photo covers the initials rather than replacing them, so a missing file');
out.push('   degrades to a monogram instead of an empty circle. */');
out.push('.pf-avatar-photo[data-avatar] { background-size: cover; background-position: center; }');
out.push('.pf-avatar-photo[data-avatar] > * { visibility: hidden; }');
out.push('');

let bytes = 0;
for (const f of files) {
  const key = basename(f, extname(f)).toLowerCase();
  const buf = readFileSync(`${DIR}/${f}`);
  bytes += buf.length;
  out.push(`.pf-avatar-photo[data-avatar="${key}"] {`);
  out.push(`  background-image: url(data:${MIME[extname(f).toLowerCase()]};base64,${buf.toString('base64')});`);
  out.push('  color: transparent;');
  out.push('}');
  out.push('');
}

const css = out.join('\n');
writeFileSync('dist/avatars.css', css);

console.log(`built dist/avatars.css  (${(css.length / 1024).toFixed(0)} KB)`);
if (!files.length) {
  console.log('avatars          : 0 — assets/avatars/ is empty, so every .avatar keeps its initials');
  console.log('                   drop .png/.jpg/.webp files there named after the person, e.g. aisha-bello.png');
} else {
  console.log(`avatars          : ${files.length} (${(bytes / 1024).toFixed(0)} KB of source images)`);
  console.log(`                   ${files.map((f) => basename(f, extname(f))).join(', ')}`);
}
