#!/usr/bin/env node
// Build the Figma-side collector for `check-icon-drift.mjs`, from that check's own source.
//
//   node scripts/build-figma-icon-digest.mjs [outputPath]
//
// WHY THIS EXISTS, AND IT IS NOT A HYPOTHETICAL. The collector used to live as a snippet in the
// check's header comment. The check's comparison was then rewritten twice — rounded text, then
// skeleton plus counts plus sums — and the snippet was not, so the documented instructions produced
// a digest file in a format the check now REFUSES. It failed safe, because `formatError` refuses an
// old-format file rather than reporting 287 drifted icons, but the instructions were still wrong
// and would have wasted the next person's afternoon.
//
// A snippet in a comment is a hand-copy of code, and this repo has now been bitten by a hand-copy
// three separate times: the rebind rule pasted into use_figma, the icon collector here, and the
// four "corrected" icon rows. So the collector is GENERATED from the check's own `shape()`,
// `digest()` and `NUMBER`, and `verify-generated.mjs` gates it — change the comparison without
// rebuilding and `npm run verify` fails rather than leaving a stale recipe to be followed.
//
// The generated script's own job is small and deliberate: enumerate the Icons page, export each
// component, and print the four fields the check reads. It sweeps the page twice and refuses to
// emit anything if the two counts disagree, because a cold `findAll` under-reports per PREDICATE
// and that has produced a wrong number in this repo on three separate occasions.
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const CHECK = 'scripts/check-icon-drift.mjs';
const DEFAULT_OUT = 'docs/figma-icon-digest.js';

// The three exports the collector needs, lifted verbatim so the two sides cannot disagree about
// what a digest IS. Cut by marker rather than by line number: an edit above `differs` must not
// silently change what gets inlined.
export function inlineShape(source) {
  const from = source.indexOf('export function digest(s) {');
  const to = source.indexOf('// Same drawing within the precision');
  if (from < 0 || to < 0 || to <= from) {
    throw new Error(`${CHECK} no longer has the markers this build cuts between`);
  }
  return source.slice(from, to)
    .replace(/^export /gm, '')
    .trimEnd();
}

export function build(out = DEFAULT_OUT) {
  const shape = inlineShape(readFileSync(CHECK, 'utf8'));
  const text = `// GENERATED by scripts/build-figma-icon-digest.mjs — do not edit. Rebuild with npm run build.
//
// Paste into the Figma MCP use_figma tool, run it, and write the result to
// tokens/_raw/figma-icon-digests.json. Then: npm run icons:check
//
// The digest definition below is inlined verbatim from ${CHECK}, so the collector and the
// comparison cannot disagree about what a digest is. verify-generated.mjs fails if this drifts.

${shape}

// ---------------------------------------------------------------------------
const page = figma.root.children.find((p) => p.name.trim() === 'Icons');
if (!page) throw new Error('no page named Icons');
await page.loadAsync();

// Two sweeps, and nothing is emitted unless they agree. A cold findAll under-reports per PREDICATE:
// this repo has had 2-of-15, 38-of-277 and 103-of-203 from a first pass, each settling on a re-run
// with no writes in between.
const count = () => page.findAll((x) => x.type === 'COMPONENT').length;
const a = count();
const b = count();
if (a !== b) return JSON.stringify({ REFUSED: 'two sweeps disagree — cold traversal', counts: [a, b] });

const out = [];
for (const n of page.findAll((x) => x.type === 'COMPONENT')) {
  const s = shape(await n.exportAsync({ format: 'SVG_STRING' }));
  out.push({ id: n.id, name: n.name, sk: s.sk, counts: s.counts, sums: s.sums });
}
return JSON.stringify(out);
`;
  writeFileSync(out, text);
  return { out, bytes: text.length };
}

let failures = 0;
const miss = (m) => { console.log(`  MISS: ${m}`); failures++; };

function selfTest() {
  const src = readFileSync(CHECK, 'utf8');
  const inlined = inlineShape(src);

  if (/^export /m.test(inlined)) miss('an export keyword survived — a plugin sandbox has no module system');
  if (!/function shape\(/.test(inlined)) miss('shape() did not make it into the inlined source');
  if (!/const NUMBER =/.test(inlined)) miss('NUMBER did not make it in — the parser is the part that was wrong twice');
  if (/function differs/.test(inlined)) miss('differs() must NOT be inlined — the collector measures, it does not judge');
  if (/process\./.test(inlined)) miss('the inlined source references process, which does not exist in Figma');

  // Cutting by marker means a restructure fails loudly rather than inlining the wrong span.
  try { inlineShape('const a = 1;\n'); miss('a source with no markers must throw rather than inline everything'); }
  catch { /* expected */ }

  const dir = mkdtempSync(join(tmpdir(), 'pf-icondigest-'));
  try {
    const out = join(dir, 'generated.js');
    build(out);
    if (!existsSync(out)) miss('build ignored its output argument — the gate would compare a file against itself');
    const text = readFileSync(out, 'utf8');
    try { new Function('figma', `return (async () => {${text}})()`); }
    catch (e) { miss(`the generated collector does not parse: ${e.message}`); }

    // It must emit exactly the four fields the check reads, or the file it writes gets refused.
    for (const field of ['id:', 'name:', 'sk:', 'counts:', 'sums:']) {
      if (!text.includes(field)) miss(`the collector must emit ${field} — check-icon-drift refuses a digest without it`);
    }
    if (!text.includes('two sweeps disagree')) miss('the collector must refuse to emit when its sweeps disagree');
  } finally { rmSync(dir, { recursive: true, force: true }); }

  if (failures) { console.log(`self-test FAILED — ${failures} check(s) did not catch what they exist to catch`); process.exit(1); }
  console.log('self-test passed — the digest definition inlines without exports or process, differs() is left behind '
    + 'because a collector measures rather than judges, a restructured source throws rather than inlining the wrong '
    + 'span, the generated collector PARSES as a plugin body, emits every field the check reads, and refuses to emit '
    + 'when its two sweeps disagree');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--self-test')) { selfTest(); process.exit(0); }
  const r = build(process.argv[2] || DEFAULT_OUT);
  console.log(`wrote ${r.out} — ${r.bytes} bytes, digest definition inlined from ${CHECK}`);
}
