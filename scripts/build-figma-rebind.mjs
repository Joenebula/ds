#!/usr/bin/env node
// Build the Figma-side driver that retires a DEPRECATED COLOURS style, from the one rule module.
//
//   node scripts/build-figma-rebind.mjs [outputPath]
//
// WHY THIS IS GENERATED AND NOT WRITTEN. The decision lives in scripts/lib/rebind-rule.mjs, where
// twelve mutants hold it. The Figma plugin sandbox cannot import a module, so the driver needs the
// rule INLINE — and a hand-copied second copy is how a fixed rule keeps being run in its broken
// form. So the driver is generated from the module's own source, and `verify-generated.mjs` gates
// it: if the rule changes and this is not rebuilt, `npm run verify` fails rather than letting a
// stale copy be pasted into Figma and believed.
//
// THE DRIVER'S OWN JOB is only the three things the rule cannot do for itself, and each one is a
// lesson that cost a cycle:
//
//   * SWEEP TWICE AND REFUSE TO PROCEED UNLESS THE RUNS AGREE. A cold findAll under-reports, per
//     PREDICATE, not merely per session: one census read 2 of 15 variants, another read 38 of 277,
//     and both settled on a re-run with no writes in between.
//   * RESOLVE BY MODE NAME, never by position or defaultModeId. "Default" is whichever mode a
//     designer left selected, and a dark-first collection resolved by position inverts the system.
//   * LOG EVERY NODE ID IT WRITES. Eighteen edits once could not be told apart from the bindings
//     already there, because the run recorded a count and not its targets.
import { readFileSync, writeFileSync, mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const RULE = 'scripts/lib/rebind-rule.mjs';
const DEFAULT_OUT = 'docs/figma-rebind-deprecated.js';

// The rule module, with its module plumbing removed: no `export` keywords, and nothing from the
// self-test, which needs `process` and has no business in a plugin sandbox. Cutting at the marker
// rather than by counting lines means an edit above it cannot silently change what gets inlined.
export function inlineRule(source) {
  const marker = 'let failures = 0;';
  const i = source.indexOf(marker);
  if (i < 0) throw new Error(`${RULE} no longer has the self-test marker this build cuts at`);
  return source.slice(0, i)
    .replace(/^#!.*\n/, '')        // a shebang is a syntax error inside a plugin script, and the
                                   // first build of this shipped one because nothing parsed the output
    .replace(/^export /gm, '')
    .trimEnd();
}

export function build(out = DEFAULT_OUT) {
  const rule = inlineRule(readFileSync(RULE, 'utf8'));
  const text = `// GENERATED by scripts/build-figma-rebind.mjs — do not edit. Rebuild with npm run build.
//
// Paste into the Figma MCP use_figma tool to retire DEPRECATED COLOURS styles safely.
// List them in STYLE_NAMES, run it, read the report. IT WRITES NOTHING until you also set
// WRITE = true: the report names every node it would change and every node it HOLDS with the
// reason, and the holds are the part worth reading before anything moves. Every id it writes is
// printed in the four columns tokens/_raw/deprecated-rebinds-applied.tsv takes, so a run can be
// checked or undone.
//
// Several styles in one run share ONE traversal of the file. Sweeping per style would walk 16
// pages once per style to answer one question about the collection, and would hand every style its
// own cold first pass to get wrong.
//
// The decision below is inlined verbatim from ${RULE}, where twelve mutants hold it.
// verify-generated.mjs fails if this copy drifts from that source.

const STYLE_NAMES = ['DEPRECATED COLOURS/CHANGE ME'];
const WRITE = false;   // REPORT ONLY. Every other script here reports by default and writes with
                       // --write; this one wrote the moment it was pasted, which is the wrong
                       // default for the only tool in the repo whose mistakes land in Figma.
const SKIP_PAGES = /WIKI|STYLE GUIDE|DOCUMENT MANAGEMENT/;   // documentation, not the shipped library

${rule}

// ---------------------------------------------------------------------------
const hex = (c) => '#' + ['r','g','b'].map((k) => Math.round(c[k] * 255).toString(16).padStart(2, '0')).join('').toUpperCase();

const styles = await figma.getLocalPaintStylesAsync();

// Every variable, and both of its modes resolved BY NAME. An alias chain is followed to a literal;
// a collection with no Darkmode is mode-stable, which is a fact about it rather than a gap.
const cols = await figma.variables.getLocalVariableCollectionsAsync();
const all = new Map();
for (const c of cols) for (const id of c.variableIds) {
  const v = await figma.variables.getVariableByIdAsync(id);
  if (v) all.set(v.id, { v, c });
}
const resolve = async (entry, want) => {
  let { v, c } = entry;
  let mode = c.modes.find((m) => new RegExp(want, 'i').test(m.name)) || c.modes[0];
  let val = v.valuesByMode[mode.modeId];
  for (let i = 0; val && val.type === 'VARIABLE_ALIAS' && i < 10; i++) {
    const t = all.get(val.id);
    if (!t) return null;
    const m = t.c.modes.find((x) => new RegExp(want, 'i').test(x.name)) || t.c.modes[0];
    val = t.v.valuesByMode[m.modeId];
  }
  return val && typeof val === 'object' && 'r' in val ? val : null;
};
const candidates = [];
for (const e of all.values()) {
  if (e.v.resolvedType !== 'COLOR') continue;
  const l = await resolve(e, 'light');
  if (!l) continue;
  const d = e.c.modes.some((m) => /dark/i.test(m.name)) ? await resolve(e, 'dark') : null;
  candidates.push({ name: e.v.name, collection: e.c.name, light: hex(l), dark: d ? hex(d) : null, scopes: e.v.scopes || [], _v: e.v });
}

// ONE TRAVERSAL FOR EVERY STYLE ASKED FOR. Sweeping per style would walk the file 46 times to
// answer one question about it, and would give each style its own cold first pass to get wrong.
const wanted = new Map();          // styleId -> { name, style, VALUE }
const problems = [];
for (const name of STYLE_NAMES) {
  const style = styles.find((s) => s.name === name);
  if (!style) { problems.push({ style: name, ERROR: 'no such paint style' }); continue; }
  if (!style.paints[0] || style.paints[0].type !== 'SOLID') { problems.push({ style: name, ERROR: 'not a solid paint style' }); continue; }
  wanted.set(style.id, { name, style, VALUE: hex(style.paints[0].color) });
}

const sweep = async () => {
  const found = [];
  for (const p of figma.root.children) {
    if (SKIP_PAGES.test(p.name)) continue;
    await p.loadAsync();
    for (const n of p.findAll((x) => wanted.has(x.fillStyleId) || wanted.has(x.strokeStyleId))) found.push(n);
  }
  return found;
};
await sweep();                       // warm-up: its count is not evidence
const a = await sweep();
const b = await sweep();
if (a.length !== b.length) return JSON.stringify({ REFUSED: 'two sweeps disagree — cold traversal', counts: [a.length, b.length] });

const backdropDark = async (node) => {
  let q = node.parent;
  while (q && q.type !== 'PAGE') {
    const f = q.fills;
    if (Array.isArray(f) && f[0] && f[0].type === 'SOLID' && f[0].visible !== false) {
      const bv = q.boundVariables && q.boundVariables.fills;
      if (bv && bv[0]) {
        const e = all.get(bv[0].id);
        if (e) { const d = await resolve(e, 'dark'); if (d) return hex(d); }
      }
      return hex(f[0].color);        // a static or style-painted panel does not darken, and that matters
    }
    q = q.parent;
  }
  return null;
};

const per = new Map();               // style name -> { before, applied[], held{}, notes[] }
for (const w of wanted.values()) per.set(w.name, { value: w.VALUE, before: 0, applied: [], held: {}, notes: [] });

for (const n of b) {
  for (const role of ['fill', 'stroke']) {
    const id = role === 'fill' ? n.fillStyleId : n.strokeStyleId;
    const w = wanted.get(id);
    if (!w) continue;
    const r = per.get(w.name);
    r.before++;
    const verdict = chooseToken({ value: w.VALUE, role, nodeType: n.type, candidates, backdropDark: await backdropDark(n) });
    if (!verdict.apply) {
      const key = role + ':' + n.type + ' — ' + verdict.reason;
      r.held[key] = (r.held[key] || 0) + 1;
      continue;
    }
    if (WRITE) {
      const variable = candidates.find((c) => c.name === verdict.variable)._v;
      const paints = role === 'fill' ? n.fills : n.strokes;
      const base = (Array.isArray(paints) && paints[0])
        ? JSON.parse(JSON.stringify(paints))[0]
        : { type: 'SOLID', color: w.style.paints[0].color };
      if (role === 'fill') {
        await n.setFillStyleIdAsync('');
        n.fills = [figma.variables.setBoundVariableForPaint(base, 'color', variable)];
      } else {
        await n.setStrokeStyleIdAsync('');
        n.strokes = [figma.variables.setBoundVariableForPaint(base, 'color', variable)];
      }
    }
    r.applied.push(n.id + '\\t' + role + '\\t' + w.name.replace('DEPRECATED COLOURS/', '') + '\\t' + verdict.variable);
    if (verdict.note) r.notes.push(n.id + ' — ' + verdict.note);
  }
}

const after1 = (await sweep()).length;
const after2 = (await sweep()).length;
return JSON.stringify({
  WROTE: WRITE,
  sweptNodes: b.length, after: after1, afterAgrees: after1 === after2,
  problems,
  styles: [...per.entries()].map(([style, r]) => ({
    style, value: r.value, before: r.before, count: r.applied.length,
    applied: r.applied,   // WROTE false: what it WOULD change. true: paste into deprecated-rebinds-applied.tsv
    held: r.held, notes: r.notes,
  })),
});
`;
  writeFileSync(out, text);
  return { out, bytes: text.length };
}

let failures = 0;
const miss = (m) => { console.log(`  MISS: ${m}`); failures++; };

// Enough of Figma to RUN the generated driver: one white paint style on one text node, and one
// semantic variable at #FFFFFF scoped TEXT_FILL, so the rule has exactly one candidate and returns
// APPLY. Every mutating call is recorded, which is what the WRITE flag is then measured by — a
// string search for `if (WRITE)` would pass on a driver that wrote anyway one line lower.
function fakeFigma() {
  const writes = [];
  const white = { r: 1, g: 1, b: 1 };
  const style = { id: 'S:1', name: 'DEPRECATED COLOURS/CHANGE ME', paints: [{ type: 'SOLID', color: white }] };
  const node = {
    id: '1:1', type: 'TEXT', fillStyleId: 'S:1', strokeStyleId: '',
    fills: [{ type: 'SOLID', color: white }], strokes: [],
    setFillStyleIdAsync: async (v) => { writes.push(`setFillStyleIdAsync(${JSON.stringify(v)})`); },
    setStrokeStyleIdAsync: async (v) => { writes.push(`setStrokeStyleIdAsync(${JSON.stringify(v)})`); },
  };
  const page = { type: 'PAGE', name: 'Forms', loadAsync: async () => {}, findAll: (p) => [node].filter(p) };
  node.parent = page;
  const variable = {
    id: 'v1', name: 'Text/Always White', resolvedType: 'COLOR', scopes: ['TEXT_FILL'],
    valuesByMode: { l: white, d: white },
  };
  const figma = {
    root: { children: [page] },
    getLocalPaintStylesAsync: async () => [style],
    variables: {
      getLocalVariableCollectionsAsync: async () => [{
        name: 'Semantic', variableIds: ['v1'],
        modes: [{ modeId: 'l', name: 'Lightmode' }, { modeId: 'd', name: 'Darkmode' }],
      }],
      getVariableByIdAsync: async (id) => (id === 'v1' ? variable : null),
      setBoundVariableForPaint: (paint, field, v) => { writes.push(`setBoundVariableForPaint(${v.name})`); return paint; },
    },
  };
  return { figma, writes };
}

const run = (text, figma) => new Function('figma', `return (async () => {${text}})()`)(figma);

async function selfTest() {
  const src = readFileSync(RULE, 'utf8');
  const inlined = inlineRule(src);

  // The defect this self-test was written for: the first build inlined the rule's SHEBANG, and the
  // generated file was a syntax error from its second line. Nothing parsed the output, so nothing
  // said so — a builder that emits unusable bytes and reports success is the `--` problem in a new
  // place.
  if (/^#!/m.test(inlined)) miss('a shebang survived inlining — the generated plugin script would not parse');
  if (/^export /m.test(inlined)) miss('an export keyword survived — a plugin sandbox has no module system');
  if (/process\./.test(inlined)) miss('the inlined rule references process, which does not exist in Figma');
  if (!/function chooseToken/.test(inlined)) miss('the rule itself did not make it into the inlined source');

  // The cut is by MARKER, so a restructure of the rule fails loudly here instead of silently
  // inlining a self-test or half a function.
  try { inlineRule('const a = 1;\n'); miss('a source with no marker must throw rather than inline everything'); }
  catch { /* expected */ }

  // The whole output must PARSE as what it is: the body of an async function with `figma` in scope.
  const dir = mkdtempSync(join(tmpdir(), 'pf-rebind-'));
  try {
    const out = join(dir, 'generated.js');
    build(out);
    if (!existsSync(out)) miss('build ignored its output argument — the gate would compare a file against itself');
    const text = readFileSync(out, 'utf8');
    try { new Function('figma', `return (async () => {${text}})()`); }
    catch (e) { miss(`the generated script does not parse: ${e.message}`); }
    if (!text.includes('two sweeps disagree')) miss('the generated driver must refuse to write when its sweeps disagree');
    if (!text.includes('applied.push')) miss('the generated driver must log every node id it writes');

    // REPORT BY DEFAULT, and proved by RUNNING it rather than by reading it. The driver used to
    // write the moment it was pasted, which is the wrong default for the one tool here whose
    // mistakes land in someone else's file.
    if (!/^const WRITE = false;/m.test(text)) miss('the generated driver must default to WRITE = false');
    let f = fakeFigma();
    let report = JSON.parse(await run(text, f.figma));
    let one = (report.styles || [])[0] || {};
    if (f.writes.length) miss(`a default run must touch NOTHING in Figma, and it called: ${f.writes.join(', ')}`);
    if (report.WROTE !== false) miss('a default run must report WROTE false, so a reader cannot mistake a dry run for a done one');
    if (one.count !== 1) miss(`a default run must still report what it WOULD change (count ${one.count})`);
    if (!String(one.applied).includes('Text/Always White')) miss('and it must name the variable it would bind');

    // A style asked for that the file does not have must be NAMED, never silently absent from the
    // report — the same rule the rest of this repo applies to an unexplained absence.
    const two = JSON.parse(await run(text.replace("['DEPRECATED COLOURS/CHANGE ME']",
      "['DEPRECATED COLOURS/CHANGE ME', 'DEPRECATED COLOURS/Not here']"), fakeFigma().figma));
    if (!JSON.stringify(two.problems || []).includes('Not here')) miss('a style the file does not hold must be reported by name, not dropped');
    if ((two.styles || []).length !== 1) miss('and the styles it DOES hold must still be measured');

    // ...and the flag must actually be the thing holding it back, or `WRITE = false` is decoration.
    f = fakeFigma();
    report = JSON.parse(await run(text.replace('const WRITE = false;', 'const WRITE = true;'), f.figma));
    if (report.WROTE !== true) miss('with WRITE set, the report must say so');
    if (!f.writes.some((w) => w.startsWith('setFillStyleIdAsync'))) miss('with WRITE set, the retired style must actually be cleared off the node');
    if (!/STYLE_NAMES = \[/.test(text)) miss('the driver must take a LIST of styles — one traversal answers the whole collection');
    if (!f.writes.some((w) => w.includes('setBoundVariableForPaint(Text/Always White)'))) miss('with WRITE set, the variable must actually be bound');
  } finally { rmSync(dir, { recursive: true, force: true }); }

  if (failures) { console.log(`self-test FAILED — ${failures} check(s) did not catch what they exist to catch`); process.exit(1); }
  console.log('self-test passed — the rule inlines without its shebang, exports or self-test, a restructured source '
    + 'throws rather than inlining the wrong span, the generated driver PARSES as a plugin body, and it still carries '
    + 'both the refuse-on-disagreement sweep and the id log; and, RUN against a stub Figma, it touches nothing at '
    + 'all by default while still reporting what it would bind, writes only once WRITE is set, takes a LIST of '
    + 'styles through one traversal, and names a style the file does not hold rather than dropping it');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--self-test')) { await selfTest(); process.exit(0); }
  const r = build(process.argv[2] || DEFAULT_OUT);
  console.log(`wrote ${r.out} — ${r.bytes} bytes, rule inlined from ${RULE}`);
}
